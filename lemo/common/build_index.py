#!/usr/bin/env python3
"""Assemble index.html: sketchnote engine (from the library demo) + this film's drawings + camera."""
import re, os, sys
LIB = os.environ.get('LIB', '/root/lemo-opuscar')
demo = open(f'{LIB}/styles/sketchnote/demo/index.html', encoding='utf-8').read().split('\n')
eng = '\n'.join(demo[16:252])     # const W..bullet()
eng = eng.replace('const W = 1920, H = 1080, FPS = 24;', 'const W = 1080, H = 1920, FPS = 24;')
eng = eng.replace("{ f, align: 'center', jit: 0.7 }, t0 + d * 0.8, o.td)", "{ f, align: 'center', jit: 0.7, col: o.tcol || INK }, t0 + d * 0.8, o.td)")
eng = eng.replace("acc: [255, 205, 40], accA: 0.80, accD: [245, 170, 0], accS: [232, 140, 0]", "acc: [128, 0, 128], accA: 0.74, accD: [100, 0, 100], accS: [150, 40, 150]")
head = '''<!doctype html>
<html><head><meta charset="utf-8">
<style>
@font-face{font-family:KB;src:url(fonts/Kalam-Bold.woff2);font-display:block}
@font-face{font-family:PH;src:url(fonts/PatrickHand-Regular.woff2);font-display:block}
html,body{margin:0;background:#fbfaf6;overflow:hidden}
canvas{display:block}
</style></head>
<body><canvas id="c" width="1080" height="1920"></canvas>
<script>
// Sketchnote, Manetrust purple accent. Generated by build_index.py (engine + film.js + tail.js).
'''
film_dir = os.path.abspath(sys.argv[1])
common = os.path.dirname(os.path.abspath(__file__))
parts = open(os.path.join(common, 'parts.js'), encoding='utf-8').read()
tail = open(os.path.join(common, 'tail.js'), encoding='utf-8').read()
film = open(os.path.join(film_dir, 'film.js'), encoding='utf-8').read()
open(os.path.join(film_dir, 'index.html'), 'w', encoding='utf-8').write(head + eng + '\n' + parts + '\n' + film + '\n' + tail + '\n</script>\n</body></html>\n')
print('index.html written')
